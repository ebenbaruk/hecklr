"""Generate the CLI and configuration reference pages from the code they document.

The pages are committed so the docs site builds without importing Hecklr, and
``tests/docs/test_reference_current.py`` fails when they drift from the code::

    uv run python docs/scripts/gen_reference.py           # rewrite the pages
    uv run python docs/scripts/gen_reference.py --check   # exit 1 if a page is stale
"""

import argparse
import ast
import enum
import inspect
import itertools
import os
import subprocess
import sys
import textwrap
import types
from collections.abc import Iterator
from pathlib import Path
from typing import Annotated, Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from hecklr.config import ProjectConfig
from hecklr_schemas import Persona, Scenario, World
from hecklr_schemas.scenario import SuccessCriterion

DOCS = Path(__file__).resolve().parents[1]
CLI_PAGE = DOCS / "reference" / "cli.md"
CONFIG_PAGE = DOCS / "reference" / "configuration.md"

_GENERATED = (
    "<!-- Generated by docs/scripts/gen_reference.py from the code; do not edit by hand. -->\n\n"
)


# --- CLI ------------------------------------------------------------------------------------


def cli_page() -> str:
    """Markdown for every ``hecklr`` command, from Typer's own docs generator."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "typer",
            "hecklr.cli",
            "utils",
            "docs",
            "--name",
            "hecklr",
            "--title",
            "CLI reference",
        ],
        capture_output=True,
        text=True,
        check=True,
        env={**os.environ, "NO_COLOR": "1", "TERM": "dumb"},
    )
    return _GENERATED + result.stdout


# --- configuration --------------------------------------------------------------------------


def config_page() -> str:
    """Markdown for ``hecklr.yaml`` and the scenario, persona and world files, field by field."""
    parts = [
        _GENERATED,
        "# Configuration reference\n\n",
        "Every file Hecklr reads is validated against these models before anything runs; an "
        "unknown key or a wrong type is an error with its file and line. Fields ending in `_env` "
        "name the environment variable that holds a secret: secrets never go in these files.\n\n",
    ]
    for title, root in (
        ("hecklr.yaml", ProjectConfig),
        ("Scenario files", Scenario),
        ("Persona files", Persona),
        ("World files", World),
    ):
        parts.append(f"## {title}\n\n")
        for model in _models(root):
            parts.append(_model_section(model))
    parts.append("## Success criteria\n\n")
    parts.append(
        "Each entry of a scenario's `success` list is one of these, chosen by its `type`.\n\n"
    )
    for model in _union_members(SuccessCriterion):
        parts.append(_model_section(model))
    return "".join(parts)


def _models(root: type[BaseModel]) -> list[type[BaseModel]]:
    """``root`` and every model reachable from its fields, depth first, each once."""
    seen: list[type[BaseModel]] = []

    def visit(model: type[BaseModel]) -> None:
        if model in seen:
            return
        seen.append(model)
        for field in model.model_fields.values():
            for nested in _nested_models(field.annotation):
                visit(nested)

    visit(root)
    criteria = set(_union_members(SuccessCriterion))
    return [model for model in seen if model not in criteria]


def _nested_models(annotation: Any) -> Iterator[type[BaseModel]]:
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        yield annotation
        return
    for arg in get_args(annotation):
        yield from _nested_models(arg)


def _union_members(annotation: Any) -> list[type[BaseModel]]:
    return list(_nested_models(annotation))


def _model_section(model: type[BaseModel]) -> str:
    docs = _attribute_docs(model)
    lines = [
        f"### {_model_title(model)} {{ #{_anchor(model)} }}",
        "",
        _clean(inspect.getdoc(_documented(model)) or ""),
        "",
        "| Field | Type | Default | Description |",
        "| --- | --- | --- | --- |",
    ]
    for name, field in model.model_fields.items():
        key = field.alias or name
        required = field.is_required()
        default = "required" if required else _config_default(field)
        description = docs.get(name, "")
        kind = _type_name(field.annotation)
        lines.append(f"| `{key}` | {kind} | {default} | {_cell(description)} |")
    return "\n".join(lines) + "\n\n"


def _documented(model: type[BaseModel]) -> type[BaseModel]:
    """The schema class a CLI-side widening (``hecklr.config``, RFC 0010a) stands in for."""
    if model.__module__ == "hecklr.config":
        base = model.__mro__[1]
        assert issubclass(base, BaseModel)  # noqa: S101 -- the widenings subclass schema models
        return base
    return model


def _model_title(model: type[BaseModel]) -> str:
    model = _documented(model)
    type_field = model.model_fields.get("type")
    if type_field is not None and get_origin(type_field.annotation) is Literal:
        values = ", ".join(f"`{value}`" for value in get_args(type_field.annotation))
        return f"{model.__name__} ({values})"
    return model.__name__


def _anchor(model: type[BaseModel]) -> str:
    return _documented(model).__name__.lower()


def _attribute_docs(model: type[BaseModel]) -> dict[str, str]:
    """Field docstrings (the string literal right under a field), from this class and its bases."""
    docs: dict[str, str] = {}
    for cls in reversed(model.__mro__):
        if not (inspect.isclass(cls) and issubclass(cls, BaseModel)) or cls is BaseModel:
            continue
        try:
            source = textwrap.dedent(inspect.getsource(cls))
        except (OSError, TypeError):
            # Classes built at runtime have no source; their fields simply go undocumented.
            continue
        body = ast.parse(source).body[0]
        assert isinstance(body, ast.ClassDef)  # noqa: S101 -- getsource of a class is a class
        statements = body.body
        for current, following in itertools.pairwise(statements):
            if (
                isinstance(current, ast.AnnAssign)
                and isinstance(current.target, ast.Name)
                and isinstance(following, ast.Expr)
                and isinstance(following.value, ast.Constant)
                and isinstance(following.value.value, str)
            ):
                docs[current.target.id] = inspect.cleandoc(following.value.value)
    return docs


def _type_name(annotation: Any) -> str:
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Annotated:
        return _type_name(args[0])
    if origin is Literal:
        return " \\| ".join(f"`{_literal(value)}`" for value in args)
    if origin in (Union, types.UnionType):
        return " \\| ".join(_type_name(arg) for arg in args)
    if origin in (list, tuple, dict):
        inner = ", ".join(_type_name(arg) for arg in args if arg is not Ellipsis)
        return f"{origin.__name__}[{inner}]"
    if annotation is type(None):
        return "null"
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        return f"[{_documented(annotation).__name__}](#{_anchor(annotation)})"
    if inspect.isclass(annotation) and issubclass(annotation, enum.Enum):
        return " \\| ".join(f"`{member.value}`" for member in annotation)
    return getattr(annotation, "__name__", str(annotation))


def _literal(value: object) -> str:
    return value.value if isinstance(value, enum.Enum) else str(value)


def _config_default(field: FieldInfo) -> str:
    if field.default_factory is not None:
        default: object = field.default_factory()  # type: ignore[call-arg]  # zero-arg factories only
    else:
        default = field.default
    if default is PydanticUndefined or default is None:
        return ""
    if isinstance(default, BaseModel):
        return "see its fields"
    if isinstance(default, enum.Enum):
        default = default.value
    if default in ({}, []):
        return ""
    return f"`{_yaml_scalar(default)}`"


def _yaml_scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, tuple):
        return "[" + ", ".join(_yaml_scalar(item) for item in value) + "]"
    return str(value)


# --- helpers --------------------------------------------------------------------------------


def _clean(text: str) -> str:
    """Docstrings use reST double backticks; Markdown wants single ones."""
    return inspect.cleandoc(text).replace("``", "`")


def _cell(text: str) -> str:
    return _clean(text).replace("\n\n", "<br>").replace("\n", " ").replace("|", "\\|")


PAGES = {CLI_PAGE: cli_page, CONFIG_PAGE: config_page}


def main(argv: list[str] | None = None) -> int:
    """Write the reference pages, or with ``--check`` report the stale ones."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for page, render in PAGES.items():
        content = render().rstrip("\n") + "\n"  # one final newline, as end-of-file-fixer wants
        if args.check:
            if not page.exists() or page.read_text(encoding="utf-8") != content:
                stale.append(page)
            continue
        page.parent.mkdir(parents=True, exist_ok=True)
        page.write_text(content, encoding="utf-8")
    for page in stale:
        sys.stderr.write(f"{page.relative_to(DOCS.parent)} is stale: run {Path(__file__).name}\n")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
